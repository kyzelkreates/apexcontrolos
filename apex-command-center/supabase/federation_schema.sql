-- ────────────────────────────────
-- TENANTS
-- Each Fleet Control OS instance = one tenant
-- ────────────────────────────────
create table if not exists tenants (
  id              uuid primary key default gen_random_uuid(),
  name            text not null,
  slug            text not null unique,
  contact_email   text,
  plan            text not null default 'starter' check (plan in ('starter','growth','enterprise')),
  status          text not null default 'active' check (status in ('active','suspended','pending','offline')),
  region          text,
  metadata        jsonb default '{}',
  registered_at   timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

-- ────────────────────────────────
-- FLEET ENTITIES
-- Each tenant can have multiple fleets
-- ────────────────────────────────
create table if not exists fleet_entities (
  id                  uuid primary key default gen_random_uuid(),
  tenant_id           uuid not null references tenants(id) on delete cascade,
  name                text not null,
  version             text,
  status              text not null default 'online' check (status in ('online','degraded','offline','maintenance')),
  pairing_token       text not null,
  command_center_url  text,
  vehicle_count       integer not null default 0,
  active_vehicles     integer not null default 0,
  driver_count        integer not null default 0,
  active_drivers      integer not null default 0,
  uptime_percent      numeric(5,2) not null default 100,
  coordinates         jsonb,       -- { lat: number, lng: number }
  last_heartbeat      timestamptz,
  registered_at       timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);

create index if not exists fleet_entities_tenant_id_idx on fleet_entities(tenant_id);

-- ────────────────────────────────
-- PAIRING CODES
-- Short-lived codes generated by Fleet Control OS
-- ────────────────────────────────
create table if not exists pairing_codes (
  id          uuid primary key default gen_random_uuid(),
  code        text not null unique,        -- APEX-XXXXXXXX-XXXX-FC
  status      text not null default 'pending' check (status in ('pending','used','expired','locked')),
  tenant_id   uuid references tenants(id) on delete set null,
  fleet_id    uuid references fleet_entities(id) on delete set null,
  attempts    integer not null default 0,
  created_at  timestamptz not null default now(),
  expires_at  timestamptz not null,
  paired_at   timestamptz
);

create index if not exists pairing_codes_code_idx on pairing_codes(code);
create index if not exists pairing_codes_status_idx on pairing_codes(status);

